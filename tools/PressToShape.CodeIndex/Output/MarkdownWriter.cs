using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using PressToShape.CodeIndex.Model;

namespace PressToShape.CodeIndex.Output;

/// <summary>Writes a readable overview from the same data as the JSON, so the two never disagree. Private members and private types are left out, everything else is listed.</summary>
internal static class MarkdownWriter
{
    private const string NoDocumentation = "_(no documentation)_";

    public static void Write(IndexData data, IIndexFileSink sink)
    {
        ArgumentNullException.ThrowIfNull(data);
        ArgumentNullException.ThrowIfNull(sink);

        var projects = data.Projects.OrderBy(p => p.Name, StringComparer.Ordinal).ToList();
        var context = new Context(projects);
        var pages = new List<(string Project, string Namespace, int Types)>();

        foreach (var project in projects)
        {
            foreach (var group in project.Symbols.Where(IsListedType).GroupBy(s => s.Namespace).OrderBy(g => g.Key, StringComparer.Ordinal))
            {
                var topLevel = group.Where(s => IsTopLevel(s, context)).OrderBy(s => s.Name, StringComparer.Ordinal).ThenBy(s => s.Id, StringComparer.Ordinal).ToList();
                if (topLevel.Count == 0)
                {
                    continue;
                }

                sink.Write(IndexLayout.MarkdownPath(project.Name, group.Key), Encode(RenderPage(project, group.Key, topLevel, context)));
                pages.Add((project.Name, group.Key, group.Count()));
            }
        }

        sink.Write(IndexLayout.MarkdownReadmePath, Encode(RenderReadme(projects, pages, data.Warnings)));
    }

    private static string RenderReadme(List<ProjectIndex> projects, List<(string Project, string Namespace, int Types)> pages, IReadOnlyList<LoadProblem> warnings)
    {
        var text = new StringBuilder();
        text.Append("# Code index overview\n\n");
        text.Append("Generated by `PressToShape.CodeIndex` (schema ").Append(IndexSchema.Version).Append("). Do not edit by hand.\n");
        text.Append("Regenerate with `dotnet run --project tools/PressToShape.CodeIndex -- generate`. ");
        text.Append("Relationships marked `inferred` are not proven by the compiler. The JSON files next to this folder hold the complete data, including calls and references.\n");

        foreach (var project in projects)
        {
            text.Append("\n## ").Append(project.Name).Append("\n\n");
            text.Append("Project file: `").Append(project.Path).Append("`. ").Append(project.Symbols.Count).Append(" symbols, ").Append(project.Relationships.Count).Append(" relationships.\n\n");
            foreach (var page in pages.Where(p => p.Project == project.Name))
            {
                var name = page.Namespace.Length == 0 ? "(global namespace)" : page.Namespace;
                var link = IndexLayout.MarkdownPath(page.Project, page.Namespace)["markdown/".Length..];
                text.Append("- [").Append(name).Append("](").Append(link).Append(") (").Append(page.Types).Append(" types)\n");
            }
        }

        if (warnings.Count > 0)
        {
            text.Append("\n## Load problems\n\n");
            foreach (var warning in warnings.OrderBy(w => w.Project, StringComparer.Ordinal).ThenBy(w => w.Reason, StringComparer.Ordinal))
            {
                text.Append("- ").Append(warning.Project).Append(": ").Append(warning.Reason).Append('\n');
            }
        }

        return text.ToString();
    }

    private static string RenderPage(ProjectIndex project, string ns, List<SymbolRecord> types, Context context)
    {
        var text = new StringBuilder();
        text.Append("# ").Append(ns.Length == 0 ? "(global namespace)" : ns).Append("\n\n");
        text.Append("Project: ").Append(project.Name).Append("\n");

        foreach (var type in types)
        {
            AppendType(text, type, context, level: 2);
        }

        return text.ToString();
    }

    private static void AppendType(StringBuilder text, SymbolRecord type, Context context, int level)
    {
        text.Append('\n').Append(new string('#', level)).Append(' ').Append(DisplayName(type)).Append(" (").Append(TypeWord(type)).Append(")\n\n");
        text.Append('`').Append(TypeHeader(type)).Append("`\n\n");
        text.Append("Source: `").Append(type.File).Append(':').Append(type.StartLine).Append('-').Append(type.EndLine).Append('`');
        if (type.IsGenerated)
        {
            text.Append(" (generated)");
        }

        text.Append("\n\n");
        text.Append(type.Doc.HasDocumentation && type.Doc.Summary is { } summary ? summary : NoDocumentation).Append('\n');
        if (type.Doc.Remarks is { } remarks)
        {
            text.Append("\n").Append(remarks).Append('\n');
        }

        var members = context.Children(type.Id).Where(s => !IsType(s) && IsListed(s)).OrderBy(s => s.StartLine).ThenBy(s => s.Id, StringComparer.Ordinal).ToList();
        if (members.Count > 0)
        {
            text.Append("\n**Members**\n\n");
            foreach (var member in members)
            {
                AppendMember(text, member);
            }
        }

        AppendRelationships(text, type, context);

        foreach (var nested in context.Children(type.Id).Where(s => IsType(s) && IsListed(s)).OrderBy(s => s.Name, StringComparer.Ordinal).ThenBy(s => s.Id, StringComparer.Ordinal))
        {
            AppendType(text, nested, context, Math.Min(level + 1, 6));
        }
    }

    private static void AppendMember(StringBuilder text, SymbolRecord member)
    {
        text.Append("- `").Append(member.Accessibility).Append(' ').Append(member.Signature ?? member.Name).Append('`');
        if (member.IsGenerated || member.GeneratedFrom is not null)
        {
            text.Append(member.GeneratedFrom is { } from ? $" _(generated from `{from}`)_" : " _(generated)_");
        }

        text.Append(" - ").Append(member.Doc.HasDocumentation && member.Doc.Summary is { } summary ? summary.Replace("\n\n", " ", StringComparison.Ordinal) : NoDocumentation).Append('\n');
    }

    private static void AppendRelationships(StringBuilder text, SymbolRecord type, Context context)
    {
        var lines = new List<string>();
        foreach (var edge in context.Outgoing(type.Id))
        {
            lines.Add($"{Verb(edge.Type)} `{context.NameOf(edge.ToId)}`{Mark(edge)}");
        }

        foreach (var edge in context.Incoming(type.Id))
        {
            lines.Add($"{(edge.Type == RelationshipType.Implements ? "Implemented by" : edge.Type == RelationshipType.Inherits ? "Inherited by" : "Injected into")} `{context.NameOf(edge.FromId)}`{Mark(edge)}");
        }

        if (lines.Count == 0)
        {
            return;
        }

        text.Append("\n**Relationships**\n\n");
        foreach (var line in lines.Distinct().OrderBy(l => l, StringComparer.Ordinal))
        {
            text.Append("- ").Append(line).Append('\n');
        }
    }

    private static string Verb(RelationshipType type) => type switch
    {
        RelationshipType.Inherits => "Inherits",
        RelationshipType.Implements => "Implements",
        _ => "Depends on (constructor)",
    };

    private static string Mark(RelationshipRecord edge) =>
        edge.Confidence == Confidence.Inferred ? $" (inferred{(edge.Reason is null ? string.Empty : ": " + edge.Reason)})" : string.Empty;

    private static string TypeHeader(SymbolRecord type)
    {
        if (type.SymbolType == SymbolType.Delegate)
        {
            return $"{type.Accessibility} delegate {type.Signature ?? type.Name}";
        }

        var modifiers = type.Modifiers.Count == 0 ? string.Empty : string.Join(' ', type.Modifiers) + " ";
        var bases = new List<string>();
        if (type.BaseType is not null)
        {
            bases.Add(type.BaseType);
        }

        bases.AddRange(type.Interfaces);
        var inheritance = bases.Count == 0 ? string.Empty : " : " + string.Join(", ", bases);
        return $"{type.Accessibility} {modifiers}{TypeWord(type)} {DisplayName(type)}{inheritance}";
    }

    private static string DisplayName(SymbolRecord type) =>
        type.Namespace.Length > 0 && type.QualifiedName.StartsWith(type.Namespace + ".", StringComparison.Ordinal)
            ? type.QualifiedName[(type.Namespace.Length + 1)..]
            : type.QualifiedName;

    private static string TypeWord(SymbolRecord type) => type.SymbolType.ToString().ToLowerInvariant();

    private static bool IsType(SymbolRecord s) =>
        s.SymbolType is SymbolType.Class or SymbolType.Interface or SymbolType.Record or SymbolType.Struct or SymbolType.Enum or SymbolType.Delegate;

    private static bool IsListed(SymbolRecord s) => s.Accessibility != "private";

    private static bool IsListedType(SymbolRecord s) => IsType(s) && IsListed(s);

    private static bool IsTopLevel(SymbolRecord s, Context context) => s.ContainingId is null || !context.IsType(s.ContainingId);

    private static byte[] Encode(string text) => new UTF8Encoding(encoderShouldEmitUTF8Identifier: false).GetBytes(text);

    private sealed class Context
    {
        private readonly Dictionary<string, SymbolRecord> _byId = new(StringComparer.Ordinal);
        private readonly ILookup<string, SymbolRecord> _children;
        private readonly ILookup<string, RelationshipRecord> _outgoing;
        private readonly ILookup<string, RelationshipRecord> _incoming;

        public Context(List<ProjectIndex> projects)
        {
            var symbols = projects.SelectMany(p => p.Symbols).ToList();
            foreach (var symbol in symbols)
            {
                _byId[symbol.Id] = symbol;
            }

            _children = symbols.Where(s => s.ContainingId is not null).ToLookup(s => s.ContainingId!, StringComparer.Ordinal);
            var structural = projects.SelectMany(p => p.Relationships)
                .Where(r => r.Type is RelationshipType.Inherits or RelationshipType.Implements or RelationshipType.InjectedDependency)
                .ToList();
            _outgoing = structural.ToLookup(r => r.FromId, StringComparer.Ordinal);
            _incoming = structural.ToLookup(r => r.ToId, StringComparer.Ordinal);
        }

        public bool IsType(string id) => _byId.TryGetValue(id, out var symbol) && MarkdownWriter.IsType(symbol);

        public IEnumerable<SymbolRecord> Children(string id) => _children[id];

        public IEnumerable<RelationshipRecord> Outgoing(string id) => _outgoing[id].OrderBy(r => r.Type).ThenBy(r => r.ToId, StringComparer.Ordinal);

        public IEnumerable<RelationshipRecord> Incoming(string id) => _incoming[id].OrderBy(r => r.Type).ThenBy(r => r.FromId, StringComparer.Ordinal);

        public string NameOf(string id) => _byId.TryGetValue(id, out var symbol) ? symbol.QualifiedName : id;
    }
}
