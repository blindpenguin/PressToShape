namespace PressToShape.Core.Shapes;

/// <summary>The four corners of a rectangle, clockwise from the top left.</summary>
public enum Corner
{
    /// <summary>The corner at the left end of the top edge.</summary>
    TopLeft,

    /// <summary>The corner at the right end of the top edge.</summary>
    TopRight,

    /// <summary>The corner at the right end of the bottom edge.</summary>
    BottomRight,

    /// <summary>The corner at the left end of the bottom edge.</summary>
    BottomLeft,
}
